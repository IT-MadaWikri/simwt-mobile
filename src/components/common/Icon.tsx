interface IconProps extends LucideProps {
  name: string;
}

export default function Icon({ name, ...props }: IconProps) {
  const Glyph = ICONS[name];
  if (!Glyph && __DEV__) console.warn(`[Icon] nama ikon tidak dikenal: "${name}"`);
  const Pick = Glyph ?? CircleQuestionMark;
  return <Pick {...props} />;
}
